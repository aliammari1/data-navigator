/** LLM response that satisfies DashboardPlanSchema */
function makeLLMPlan(): DashboardPlan & {
  widgets: Array<{
    id: string;
    title: string;
    chartType: string;
    sqlIntent: string;
    dimensions: string[];
    metrics: string[];
    reasoning: string;
  }>;
} {
  return {
    title: "LLM Dashboard",
    description: "Generated by LLM",
    widgets: [
      {
        id: "kpi-llm",
        title: "KPI Overview",
        chartType: "kpi-grid",
        sqlIntent: "Compute KPIs",
        dimensions: [],
        metrics: ["amount"],
        reasoning: "summary stats",
      },
      {
        id: "trend-llm",
        title: "Amount Over Time",
        chartType: "area",
        sqlIntent: "Group by day",
        dimensions: ["day"],
        metrics: ["amount"],
        reasoning: "temporal trend",
      },
      {
        id: "bar-llm",
        title: "By Channel",
        chartType: "bar",
        sqlIntent: "Group by channel",
        dimensions: ["channel"],
        metrics: ["amount"],
        reasoning: "channel breakdown",
      },
    ],
  };
}

