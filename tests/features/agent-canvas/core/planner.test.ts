// ─── LLM error → heuristic fallback ───────────────────────────────────────────

describe("buildPlan — LLM error falls back to heuristics", () => {
  beforeEach(() => {
    mockAiReadySync.mockReturnValue(true);
  });

  it("falls back to heuristic plan when aiStructured throws", async () => {
    mockAiStructured.mockRejectedValue(new Error("model overloaded"));
    const schema = makeSchema();
    const plan = await buildPlan(schema, vi.fn());
    // Heuristic plan always includes a data-table
    const table = plan.widgets.find((w) => w.chartType === "data-table");
    expect(table).toBeDefined();
  });

  it("emits an error message mentioning the thrown error", async () => {
    mockAiStructured.mockRejectedValue(new Error("network timeout"));
    const emitted: string[] = [];
    await buildPlan(makeSchema(), (t) => emitted.push(t));
    const errMsg = emitted.find((m) => m.includes("LLM planner failed"));
    expect(errMsg).toContain("network timeout");
  });

  it("emits a 'Fallback plan' ready message after failure", async () => {
    mockAiStructured.mockRejectedValue(new Error("crash"));
    const emitted: string[] = [];
    const plan = await buildPlan(makeSchema(), (t) => emitted.push(t));
    const fallbackMsg = emitted.find((m) => m.includes("Fallback plan"));
    expect(fallbackMsg).toContain(`${plan.widgets.length} widgets`);
  });

  it("returns the same heuristic plan structure as the no-AI path on failure", async () => {
    mockAiStructured.mockRejectedValue(new Error("fail"));
    const schema = makeSchema();

    // Disable AI for comparison
    mockAiReadySync.mockReturnValue(false);
    const heuristicPlan = await buildPlan(schema, vi.fn());

    // Re-enable AI (will fail → fallback)
    mockAiReadySync.mockReturnValue(true);
    mockAiStructured.mockRejectedValue(new Error("fail"));
    const fallbackPlan = await buildPlan(schema, vi.fn());

    // Both plans should have the same widget ids in the same order
    const heuristicIds = heuristicPlan.widgets.map((w) => w.id);
    const fallbackIds = fallbackPlan.widgets.map((w) => w.id);
    expect(fallbackIds).toEqual(heuristicIds);
  });
});

